function screensStrip(game) {
  const shots = game.art.screens
    .map((src, index) => ({ src, alt: game.art_alt.screens[index] }))
    .filter((shot) => publicFileExists(shot.src));
  if (!shots.length) return "";
  const items = shots.map((shot) => {
    const [width, height] = imageSize(shot.src);
    return `<li><img src="${esc(shot.src)}" alt="${esc(shot.alt)}" width="${width}" height="${height}" loading="lazy"></li>`;
  }).join("\n        ");
  return `<section class="section wrap" aria-labelledby="screens-title">
    <h2 id="screens-title">A look inside</h2>
    <ul class="screens">
        ${items}
    </ul>
  </section>`;
}

function videoGame(game, share) {
  const platforms = ["Web Browser"];
  if (game.stores.ios) platforms.push("iOS");
  if (game.stores.android) platforms.push("Android");
  const offers = [{
    "@type": "Offer",
    name: "Free to play",
    price: "0",
    priceCurrency: "USD",
    url: SITE + game.page
  }];
  if (game.price) {
    offers.push({
      "@type": "Offer",
      name: "One-time unlock (in-app purchase)",
      description: game.unlock,
      price: game.price.slice(1),
      priceCurrency: "USD"
    });
  }
  return {
    "@context": "https://schema.org",
    "@type": "VideoGame",
    name: game.title,
    description: game.description,
    url: SITE + game.page,
    image: share.url,
    genre: "Educational",
    audience: {
      "@type": "PeopleAudience",
      suggestedMinAge: game.ageRange.min,
      suggestedMaxAge: game.ageRange.max
    },
    gamePlatform: platforms,
    applicationCategory: "GameApplication",
    offers,
    publisher: {
      "@type": "Organization",
      name: "PinkRyno Studios",
      url: SITE + "/"
    }
  };
}

