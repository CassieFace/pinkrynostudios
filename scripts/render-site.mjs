#!/usr/bin/env node
/**
 * Renders the static PinkRyno Studios site from games.json and site.json.
 * Run from the repo root: node scripts/render-site.mjs
 *
 * The mascot name and pictures come only from site.json.
 *
 * Writes pages, assets/css/themes.css, and sitemap.xml.
 * Never writes CNAME, games/space-maze/, or games/tiny-trails-beta/.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://pinkrynostudios.com";
const UPDATED = "2026-10-22";
const SUPPORT_EMAIL = "support@pinkrynostudios.com";
const MARKER = "Generated by scripts/render-site.mjs";
const RESERVED = new Set(["space-maze", "tiny-trails-beta"]);
let mascot;

