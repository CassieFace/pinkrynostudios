function isEmpty(value) {
  return value == null || value === "";
}

function isObject(value) {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

// Stops on keys an entry does not use, so a typo like "srcsmall" cannot quietly empty a slot.
function onlyKeys(value, keys, label) {
  const extra = Object.keys(value).filter((key) => !keys.includes(key));
  must(!extra.length, `${label} has unknown key(s) ${extra.join(", ")}. Use ${keys.join(", ")}.`);
}

// Records an empty slot for the end-of-build warning.
function empty(label) {
  emptySlots.push(label);
  return null;
}

// True for an entry that leaves its slot empty: null, "", or an object whose src is empty.
function emptyEntry(entry, label) {
  if (isEmpty(entry)) return true;
  if (isObject(entry) && isEmpty(entry.src)) {
    must(!sitePaths(entry).length, `${label}.src is empty, so its other files would never show. Set src, or set ${label} to null.`);
    return true;
  }
  return false;
}

const FORMAT_NAMES = { webp: "WebP", png: "PNG", jpg: "JPEG", svg: "SVG", ico: "ICO" };
function checkFormat(src, label, formats) {
  const ext = src.split(/[?#]/)[0].split(".").pop().toLowerCase().replace("jpeg", "jpg");
  must(formats.includes(ext), `${label} must be ${formats.map((format) => FORMAT_NAMES[format]).join(" or ")}: ${src}`);
  return src;
}

// A file entry that must exist and be one of formats. Returns [src, width, height].
function sizedFile(src, label, formats) {
  requireFile(src, label);
  checkFormat(src, label, formats);
  return [src, ...imageSize(src)];
}

// width and height in an entry are optional unless required is true. When set, they must match the file.
function checkStatedSize(entry, widthKey, heightKey, [src, width, height], label, required = false) {
  const fix = `set "${widthKey}": ${width} and "${heightKey}": ${height}`;
  if (required) {
    must(entry[widthKey] != null && entry[heightKey] != null,
      `${label} needs "${widthKey}" and "${heightKey}", the pixel size of ${src}. That file is ${width}x${height}, so ${fix}.`);
  } else if (entry[widthKey] == null && entry[heightKey] == null) return;
  must(entry[widthKey] === width && entry[heightKey] === height,
    `${label} says ${widthKey} ${JSON.stringify(entry[widthKey])} and ${heightKey} ${JSON.stringify(entry[heightKey])}, but ${src} is ${width}x${height}. ` +
    (required ? `Export the size you meant, or ${fix}.` : "Fix the numbers or remove them."));
}

/* One picture: null (an empty slot) or { src, src2x, width, height, alt }. src2x,
   when set, must be twice the size of src. alt is required unless the picture is
   decorative. size: "required" makes width and height required. Extra keys (like
   srcSmall) are checked by the caller. */
function picture(entry, label, { alt: needsAlt = true, formats = ["webp", "png", "jpg"], retina = true, keys = [], size = "optional" } = {}) {
  if (emptyEntry(entry, label)) return empty(label);
  must(isObject(entry), `${label} must be null or an object like { "src": "/assets/..." }`);
  onlyKeys(entry, ["src", ...(retina ? ["src2x"] : []), "width", "height", "alt", ...keys], label);
  const file = sizedFile(entry.src, label + ".src", formats);
  checkStatedSize(entry, "width", "height", file, label, size === "required");
  const [src, width, height] = file;
  let src2x = null;
  if (!isEmpty(entry.src2x)) {
    const [, w2, h2] = sizedFile(entry.src2x, label + ".src2x", formats);
    must(Math.abs(w2 - 2 * width) <= 1 && Math.abs(h2 - 2 * height) <= 1, `${label}.src2x is ${w2}x${h2}, but it should be twice ${src} (${2 * width}x${2 * height})`);
    src2x = entry.src2x;
  }
  const alt = textOrNull(entry.alt, label + ".alt");
  if (needsAlt) must(alt, `${label} needs alt text that describes the picture`);
  return { src, src2x, width, height, alt };
}

/* Rosie's wave (art.rosie.animated): an animated WebP with a same-size still for
   first paint and reduced motion, and optionally a smaller pair (srcSmall + stillSmall).
   Each wave replaces its own still at the width the browser chose, so the two must
   be exactly the same size. */
function animatedPicture(entry, label) {
  if (emptyEntry(entry, label)) return empty(label);
  must(isObject(entry), `${label} must be null or an object like { "src": "/assets/....webp", "still": "/assets/....webp" }`);
  onlyKeys(entry, ["src", "srcSmall", "still", "stillSmall", "width", "height", "widthSmall", "heightSmall", "alt"], label);
  const pair = (animKey, stillKey, widthKey, heightKey) => {
    must(!isEmpty(entry[stillKey]), `${label}.${stillKey} is needed with ${animKey}: a still frame for visitors who turn off motion`);
    const anim = sizedFile(entry[animKey], `${label}.${animKey}`, ["webp"]);
    const still = sizedFile(entry[stillKey], `${label}.${stillKey}`, ["webp"]);
    must(still[1] === anim[1] && still[2] === anim[2],
      `${label}.${animKey} (${anim[0]}) is ${anim[1]}x${anim[2]}, but ${label}.${stillKey} (${still[0]}) is ${still[1]}x${still[2]}. ` +
      "Rosie's wave replaces her still at the same display size, so each wave must be exactly the size of its still. Export both at the same size.");
    // The swap script splits srcset lists and matches img.currentSrc by its path's end,
    // so these paths must need no escaping in a srcset or a URL.
    for (const [key, file] of [[animKey, anim[0]], [stillKey, still[0]]]) {
      must(/^[\w/.-]+$/.test(file), `${label}.${key} must use only letters, digits, "-", "_", ".", and "/" in its path: ${file}`);
    }
    checkStatedSize(entry, widthKey, heightKey, anim, label);
    const bytes = statSync(join(root, sitePathToRel(anim[0]))).size;
    if (bytes > WAVE_BUDGET) heavyWaves.push([`${label}.${animKey}`, anim[0], bytes]);
    return { anim: anim[0], still: still[0], width: anim[1], height: anim[2] };
  };
  const large = pair("src", "still", "width", "height");
  let small = null;
  if (!isEmpty(entry.srcSmall)) {
    small = pair("srcSmall", "stillSmall", "widthSmall", "heightSmall");
    // Both pairs share one srcset, so the small one must be a smaller copy with the same shape.
    must(small.width < large.width, `${label}.srcSmall is ${small.width} px wide, so it is not smaller than src (${large.width} px)`);
    must(Math.abs(small.width / small.height - large.width / large.height) < 0.01,
      `${label}.srcSmall is ${small.width}x${small.height}, a different shape from src (${large.width}x${large.height}). Export a smaller copy of the same picture.`);
  } else must(isEmpty(entry.stillSmall) && entry.widthSmall == null && entry.heightSmall == null, `${label}: stillSmall, widthSmall, and heightSmall go with srcSmall`);
  // The swap script finds the still on screen by the end of img.currentSrc, so no path may end with another.
  const files = [large, small].filter(Boolean).flatMap((pair) => [pair.anim, pair.still]);
  const clash = files.find((file) => files.some((other) => other !== file && file.endsWith(other)));
  must(!clash, `${label}: ${clash} ends with another of its paths, so the wave swap could pick the wrong file. Give each file its own name.`);
  const alt = textOrNull(entry.alt, label + ".alt");
  must(alt, `${label} needs alt text that describes the picture`);
  return { large, small, alt };
}

/* A wide scene (the home hero art, a game's hero art): { src, srcSmall, width,
   height, alt }. srcSmall is optional: a smaller copy of the same picture, with
   the same shape. Phones always get srcSmall, and wider screens pick src or
   srcSmall by size, so src only loads where srcSmall would look soft. */
function scene(entry, label, { alt = true } = {}) {
  const pic = picture(entry, label, { alt, retina: false, keys: ["srcSmall"] });
  if (pic && !isEmpty(entry.srcSmall)) {
    [pic.srcSmall, pic.widthSmall, pic.heightSmall] = sizedFile(entry.srcSmall, label + ".srcSmall", ["webp", "png", "jpg"]);
    must(pic.widthSmall < pic.width, `${label}.srcSmall is ${pic.widthSmall} px wide, so it is not smaller than src (${pic.width} px)`);
    must(Math.abs(pic.widthSmall / pic.heightSmall - pic.width / pic.height) < 0.01,
      `${label}.srcSmall is ${pic.widthSmall}x${pic.heightSmall}, a different shape from src (${pic.width}x${pic.height}). Export a smaller copy of the same picture.`);
  }
  return pic;
}

// A share image (og:image): PNG or JPEG, so every app that shows link previews can read it.
function sharePicture(entry, label) {
  const pic = picture(entry, label, { formats: ["png", "jpg"], retina: false });
  if (!pic) return null;
  const type = pic.src.endsWith(".png") ? "image/png" : "image/jpeg";
  return { url: SITE + pic.src, width: pic.width, height: pic.height, type, alt: pic.alt };
}

// A file that must be exactly size x size pixels (favicons, apple-touch icon).
function squareFile(value, label, size, formats) {
  if (isEmpty(value)) return empty(label);
  const [src, width, height] = sizedFile(value, label, formats);
  must(width === size && height === size, `${label} is ${width}x${height}, expected ${size}x${size}: ${src}`);
  return src;
}

// The classic favicon: an .ico that holds at least the 16, 32, and 48 px images.
// Its <link sizes> lists every size in the file. Returns { src, sizes }.
const ICO_SIZES = [16, 32, 48];
function icoFile(value, label) {
  if (isEmpty(value)) return empty(label);
  requireFile(value, label);
  checkFormat(value, label, ["ico"]);
  const sizes = icoSizes(value);
  const missing = ICO_SIZES.filter((size) => !sizes.includes(size));
  must(!missing.length, `${label} has no ${missing.map((size) => `${size}x${size}`).join(", ")} image. It needs ${ICO_SIZES.map((size) => `${size}x${size}`).join(", ")}: ${value}`);
  return { src: value, sizes };
}

// The Organization logo in the home page's JSON-LD. Search engines want at least 112x112.
function logoFile(value, label) {
  if (isEmpty(value)) return empty(label);
  const [src, width, height] = sizedFile(value, label, ["png", "jpg", "webp"]);
  must(width >= 112 && height >= 112, `${label} is ${width}x${height}; use at least 112x112: ${src}`);
  return src;
}

// A map of square images keyed by pixel size, like { "64": "/a-64.webp", "128": "/a-128.webp" }.
// Every file must exist and really be that size. Returns [[64, "/a-64.webp"], ...], smallest first.
function sizedSet(value, label, formats) {
  if (isEmpty(value)) return empty(label);
  must(isObject(value), `${label} must be null or map pixel sizes to files, like { "64": "/path-64.webp" }`);
  const list = Object.entries(value).filter(([, src]) => !isEmpty(src)).map(([key, src]) => {
    must(/^[1-9]\d*$/.test(key), `${label} key "${key}" must be a pixel size`);
    const [, width, height] = sizedFile(src, `${label}.${key}`, formats);
    const size = Number(key);
    must(width === size && height === size, `${label}.${key} is ${width}x${height}, expected ${size}x${size}: ${src}`);
    return [size, src];
  });
  if (!list.length) return empty(label);
  return list.sort((a, b) => a[0] - b[0]);
}

// An icon: "/file.svg#symbol" (a symbol in a sprite, drawn with <use>) or a
// plain .svg, .webp, or .png file (drawn with <img>).
function artRef(value, label) {
  if (isEmpty(value)) return empty(label);
  must(typeof value === "string", `${label} must be a site path or null`);
  requireFile(value, label);
  const [file, id] = value.split("#");
  if (id === undefined) return { img: checkFormat(file, label, ["svg", "webp", "png"]) };
  must(file.endsWith(".svg") && id, `${label} must look like /assets/.../sprite.svg#symbol-id`);
  must(symbolIds(file).has(id), `${label}: ${file} has no <symbol id="${id}">`);
  return { use: value };
}

// A group of icons keyed by name. names lists every key a page can use.
function artRefs(value, label, names) {
  if (isEmpty(value)) {
    empty(label);
    return Object.fromEntries(names.map((name) => [name, null]));
  }
  must(isObject(value), `${label} must be null or an object`);
  onlyKeys(value, names, label);
  return Object.fromEntries(names.map((name) => [name, artRef(value[name], `${label}.${name}`)]));
}

const ART_KEYS = ["rosie", "headerLogo", "faviconIco", "favicon32", "appleTouch", "logo", "og", "aboutScene", "icons", "retired"];

/* The studio logo's display height: site.json art.headerLogo.displayHeight, or this
   default. The header (on wider screens) and the footer draw it that tall, and the
   phone header a little smaller. Its 1x file must be at least that tall, so the
   logo is never drawn larger than its pixels. */
const LOGO_DEFAULT_HEIGHT = 60;
// The heights site.css can draw: one rule per height, like
// .logo-h-60 { --logo-h: 60px; --logo-h-phone: 48px; }. The build adds that class to the logo.
const LOGO_HEIGHT_RULE = /\.logo-h-(\d+)\s*\{\s*--logo-h:\s*(\d+)px;\s*--logo-h-phone:\s*(\d+)px;\s*\}/g;
// The logo's widest drawing (max-width on .brand-logo and .footer-logo), and the room the
// phone header keeps for the side margins, the Menu button, and the gap (.brand-logo's
// phone max-width, calc(100vw - 136px)). Keep in step with site.css. Used for the build's
// size report only.
const LOGO_MAX_WIDTH = 360;
const PHONE_HEADER_SPARE = 136;

// Map of display height -> phone header height, read from the .logo-h-<N> rules in site.css.
function logoHeights() {
  const heights = new Map();
  for (const [, name, height, phone] of siteCss().matchAll(LOGO_HEIGHT_RULE)) {
    must(name === height, `assets/css/site.css: .logo-h-${name} sets --logo-h: ${height}px. Each .logo-h-<N> rule must draw the logo N px tall.`);
    must(Number(phone) <= Number(height), `assets/css/site.css: .logo-h-${name} draws the phone header logo taller (${phone}px) than the wide one (${height}px)`);
    heights.set(Number(name), Number(phone));
  }
  must(heights.has(LOGO_DEFAULT_HEIGHT), `assets/css/site.css needs a .logo-h-${LOGO_DEFAULT_HEIGHT} rule (the studio logo's default height), like .logo-h-60 { --logo-h: 60px; --logo-h-phone: 48px; }`);
  return heights;
}

// site.json "art": every site-wide picture. See "Art slots" in README.md.
function loadArt(map) {
  must(isObject(map), 'site.json needs an "art" object (the art map). See "Art slots" in README.md.');
  onlyKeys(map, ART_KEYS, "site.json art");
  must(map.retired == null || (Array.isArray(map.retired) && map.retired.every((src) => typeof src === "string" && src.startsWith("/"))), "site.json art.retired must be a list of site paths");
  retired = new Set(map.retired || []);
  // Every path in the map must exist, in every build mode, even in an entry a page does not show.
  for (const [src, label] of sitePaths({ ...map, retired: null })) requireFile(src, "site.json art." + label);
  const group = (value, keys, label) => {
    if (isEmpty(value)) return {};
    must(isObject(value), `${label} must be null or an object`);
    onlyKeys(value, keys, label);
    return value;
  };
  const rosie = group(map.rosie, ["static", "animated", "head", "lost"], "site.json art.rosie");
  const og = group(map.og, ["default"], "site.json art.og");
  return {
    rosieStatic: picture(rosie.static, "site.json art.rosie.static", { formats: ["webp", "png"] }),
    rosieAnimated: animatedPicture(rosie.animated, "site.json art.rosie.animated"),
    head: sizedSet(rosie.head, "site.json art.rosie.head", ["webp", "png"]),
    rosieLost: picture(rosie.lost, "site.json art.rosie.lost", { formats: ["webp", "png"] }),
    headerLogo: headerLogoPicture(map.headerLogo, "site.json art.headerLogo"),
    faviconIco: icoFile(map.faviconIco, "site.json art.faviconIco"),
    favicon32: squareFile(map.favicon32, "site.json art.favicon32", 32, ["png"]),
    appleTouch: squareFile(map.appleTouch, "site.json art.appleTouch", 180, ["png"]),
    logo: logoFile(map.logo, "site.json art.logo"),
    og: sharePicture(og.default, "site.json art.og.default"),
    aboutScene: picture(map.aboutScene, "site.json art.aboutScene"),
    icons: artRefs(map.icons, "site.json art.icons", ICON_NAMES)
  };
}

/* The studio logo, the one entry for every place the lockup shows (the header's home
   link and the footer): a PNG or WebP at 1x with src2x for HiDPI screens, never the
   heavy outlined SVG. width and height are required and must be the 1x file's real
   size; the pages take the logo's shape from them, so a wider or narrower lockup
   needs no code or CSS change. alt names the studio, because the logo is the home
   link and the footer's studio name. displayHeight (optional) picks a .logo-h-<N>
   rule in site.css. */
function headerLogoPicture(entry, label) {
  const pic = picture(entry, label, { formats: ["png", "webp"], keys: ["displayHeight"], size: "required" });
  if (!pic) return null;
  must(pic.src2x, `${label} needs src2x, a 2x copy for HiDPI screens: ${pic.width * 2}x${pic.height * 2}, twice ${pic.src}`);
  const heights = logoHeights();
  const display = entry.displayHeight ?? LOGO_DEFAULT_HEIGHT;
  must(heights.has(display),
    `${label}.displayHeight is ${JSON.stringify(entry.displayHeight)}. Use one of ${[...heights.keys()].join(", ")} ` +
    `(CSS px, the .logo-h-<N> rules in assets/css/site.css), or leave it out for ${LOGO_DEFAULT_HEIGHT}.`);
  must(pic.height >= display,
    `${label}.src (${pic.src}) is ${pic.height} px tall, but the header and footer draw it ${display} px tall` +
    `${entry.displayHeight == null ? " (the default displayHeight)" : " (displayHeight)"}. ` +
    `Export the 1x file at least ${display} px tall, with src2x at twice its size, or lower displayHeight.`);
  return { ...pic, display, phone: heights.get(display), heightClass: `logo-h-${display}` };
}

// After a build: how big the studio logo is drawn, and a warning when it is too wide to
// draw at full height (it then keeps its shape and draws smaller).
function reportLogo() {
  const logo = art.headerLogo;
  if (!logo) return;
  const wide = (height) => Math.round((height * logo.width) / logo.height);
  const fullFrom = wide(logo.phone) + PHONE_HEADER_SPARE;
  console.log(
    `Studio logo (site.json art.headerLogo): ${logo.src} ${logo.width}x${logo.height}, drawn ${wide(logo.display)}x${logo.display} ` +
    `in the header and footer, ${wide(logo.phone)}x${logo.phone} in the phone header (full size beside the Menu button on phones ${fullFrom} px wide and up).`
  );
  const problems = [];
  if (wide(logo.display) > LOGO_MAX_WIDTH) {
    problems.push(`It is ${wide(logo.display)} px wide at ${logo.display} px tall, over the ${LOGO_MAX_WIDTH} px limit, so it draws ${LOGO_MAX_WIDTH} px wide and about ${Math.floor((LOGO_MAX_WIDTH * logo.height) / logo.width)} px tall.`);
  }
  // 360 px is the narrowest common phone.
  if (fullFrom > 360) {
    const room = 360 - PHONE_HEADER_SPARE;
    problems.push(`In the phone header it is ${wide(logo.phone)} px wide at ${logo.phone} px tall, so phones narrower than ${fullFrom} px draw it smaller to fit beside the Menu button (a 360 px phone: ${room} px wide, about ${Math.floor((room * logo.height) / logo.width)} px tall).`);
  }
  if (problems.length) console.warn(`Warning: the studio logo is very wide. ${problems.join(" ")} A lower displayHeight or a less wide lockup keeps it full size.`);
}

const GAME_ART_KEYS = ["hero", "title", "wordmark", "card", "icon", "og", "screenshots"];

// A game's "art" in games.json. Every picture is optional.
function loadGameArt(game) {
  const label = `games.json ${game.id} art`;
  const map = game.art == null ? {} : game.art;
  must(isObject(map), `${label} must be an object`);
  onlyKeys(map, GAME_ART_KEYS, label);
  must(map.screenshots == null || Array.isArray(map.screenshots), `${label}.screenshots must be a list`);
  // title: the game's title lockup, the visual title of its page hero (the <h1> text stays
  // for screen readers). wordmark: the series wordmark that stands for the game on studio
  // pages, which show no game-world art. Both are outlined art, so SVG is welcome.
  const result = {
    hero: scene(map.hero, label + ".hero"),
    title: picture(map.title, label + ".title", { alt: false, formats: ["svg", "webp", "png"], retina: false }),
    wordmark: picture(map.wordmark, label + ".wordmark", { alt: false, formats: ["svg", "webp", "png"], retina: false }),
    card: picture(map.card, label + ".card", { alt: false }),
    icon: picture(map.icon, label + ".icon", { alt: false, formats: ["webp", "png"] }),
    og: sharePicture(map.og, label + ".og")
  };
  const shots = map.screenshots || [];
  if (!shots.length) empty(label + ".screenshots");
  result.screenshots = shots.map((entry, index) => picture(entry, `${label}.screenshots[${index}]`)).filter(Boolean);
  return result;
}

function reportEmptySlots() {
  if (!emptySlots.length) {
    console.log("Every art slot is filled.");
    return;
  }
  const groups = new Map();
  for (const label of emptySlots) {
    const at = label.indexOf(" art");
    const owner = label.slice(0, at);
    if (!groups.has(owner)) groups.set(owner, []);
    groups.get(owner).push(label.slice(at + 1));
  }
  const lines = [...groups].map(([owner, slots]) => `  ${owner}: ${slots.join(", ")}`);
  console.warn("Warning: empty art slots, left out of the pages:\n" + lines.join("\n"));
}

// Over budget is a warning, so an over-budget wave still builds while a lighter export is made.
function reportHeavyWaves() {
  if (!heavyWaves.length) return;
  const lines = heavyWaves.map(([label, src, bytes]) => `  ${src} (${label}) is ${bytes.toLocaleString("en-US")} bytes (${Math.round(bytes / 1024)} KB)`);
  console.warn(
    `Warning: Rosie's wave is over its ${WAVE_BUDGET.toLocaleString("en-US")}-byte (100 KB) budget per file. ` +
    "Visitors download it when they scroll to her on the home page:\n" + lines.join("\n")
  );
}

/* site.json ------------------------------------------------------------- */

function loadSite(file) {
  const site = JSON.parse(readFileSync(file, "utf8"));
  must(isObject(site), "site.json must be an object");
  // Pictures live only in the art map.
  for (const [, label] of sitePaths({ ...site, art: null })) {
    throw new Error(`site.json ${label} looks like a file path. Pictures go in site.json "art".`);
  }
  art = loadArt(site.art);
  const next = site.mascot;
  must(isObject(next), "site.json needs a mascot object");
  onlyKeys(next, ["name", "fullName", "pronouns", "species"], 'site.json mascot (pictures go in "art")');
  must(typeof next.name === "string" && next.name.trim(), "site.json needs mascot.name");
  must(typeof next.fullName === "string" && next.fullName.trim(), "site.json needs mascot.fullName");
  must(next.pronouns && typeof next.pronouns.subject === "string" && next.pronouns.subject.trim(), "site.json needs mascot.pronouns.subject");
  must(typeof next.species === "string" && next.species.trim(), "site.json needs mascot.species");
  mascot = next;

  const info = site.studio;
  must(info && typeof info === "object", "site.json needs a studio object");
  studio = {
    legalName: textOrNull(info.legalName, "site.json studio.legalName"),
    address: textOrNull(info.address, "site.json studio.address"),
    supportEmail: textOrNull(info.supportEmail, "site.json studio.supportEmail")
  };
  if (studio.supportEmail) {
    must(/^[^\s@<>"]+@[^\s@<>"]+\.[a-z]{2,}$/i.test(studio.supportEmail), "site.json studio.supportEmail must be an email address or null");
  }
  privacyLine = textOrNull(site.privacyLine, "site.json privacyLine");
  must(privacyLine, "site.json needs privacyLine (the trust strip, the one line about privacy on each page)");
  must(PRIVACY_PITCH.test(privacyLine), "site.json privacyLine is the trust strip, so it should say what it promises, like \"No ads · No tracking · No accounts\"");
}

