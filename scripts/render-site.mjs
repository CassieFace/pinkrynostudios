  writeRel("about/index.html", pageAbout());
  writeRel("privacy/index.html", pagePrivacy());
  writeRel("support/index.html", pageSupport());
  writeRel("404.html", pageNotFound());
  writeRel("sitemap.xml", sitemap(visible));
