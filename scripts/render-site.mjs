/* Output checks --------------------------------------------------------- */

const URL_TAG = /<(a|link|img|source|script|form|iframe|video|audio|use)\b([^>]*)>/gi;
const URL_ATTR = /\s(href|src|srcset|data-wave-srcset|data-wave-phone-srcset|action|poster)="([^"]*)"/gi;
const WAVE_ATTRS = new Set(["data-wave-srcset", "data-wave-phone-srcset"]);
const INLINE_SCRIPT = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;

// Every URL in the rendered files must resolve to a local file (or a file this
// build writes), use an absolute path, and leave the site only through a gated <a>.
function checkRendered(files) {
  const outputs = new Set(files.map(([rel]) => rel));
  const exists = (path) => {
    const rel = sitePathToRel(path);
    return outputs.has(rel) || existsSync(join(root, rel));
  };
  // Rosie's wave files may appear only in the data-wave attributes, so they never load up front.
  const anim = art.rosieAnimated;
  const waveFiles = new Set(anim ? [anim.large.anim, anim.small && anim.small.anim].filter(Boolean) : []);
  const problems = [];
  for (const [rel, text] of files) {
    if (rel.endsWith(".html")) {
      const ids = new Set([...text.matchAll(/\sid="([^"]+)"/g)].map((match) => match[1]));
      for (const [, tag, attrs] of text.matchAll(URL_TAG)) {
        const gatedLink = tag.toLowerCase() === "a" && /\sdata-parent-gate(?=[\s=]|$)/.test(attrs);
        for (const [, attr, raw] of attrs.matchAll(URL_ATTR)) {
          const value = raw.replaceAll("&amp;", "&");
          const urls = attr.toLowerCase().endsWith("srcset") ? value.split(",").map((part) => part.trim().split(/\s+/)[0]) : [value];
          for (const url of urls) {
            if (waveFiles.has(url) && !WAVE_ATTRS.has(attr.toLowerCase())) {
              problems.push(`${rel}: ${attr}="${url}" loads Rosie's animated wave up front. It belongs only in data-wave-srcset or data-wave-phone-srcset.`);
            }
            if (url.startsWith("#")) {
              if (url.length > 1 && !ids.has(url.slice(1))) problems.push(`${rel}: ${url} has no matching id`);
            } else if (url.startsWith("mailto:") || (url.startsWith("https://") && !url.startsWith(SITE + "/"))) {
              if (!gatedLink) problems.push(`${rel}: ${url} leaves the site, so it must be an <a> with data-parent-gate`);
            } else if (url.startsWith(SITE + "/")) {
              if (!exists(url.slice(SITE.length))) problems.push(`${rel}: ${url} has no local file`);
            } else if (/^\/(?!\/)/.test(url)) {
              if (!exists(url)) problems.push(`${rel}: ${url} does not exist`);
              else if (tag.toLowerCase() === "use") {
                const [file, id] = url.split("#");
                if (!id || !symbolIds(file).has(id)) problems.push(`${rel}: ${url} has no matching <symbol> in ${file}`);
              }
            } else {
              problems.push(`${rel}: ${attr}="${url}" must be an absolute site path (/...), a #fragment, or a gated https:// or mailto: link`);
            }
          }
        }
      }
      const note = text.match(INTERNAL_NOTES);
      if (note) problems.push(`${rel}: contains internal or placeholder text ("${note[0]}")`);
      // The CSP is style-src 'self': a style attribute or <style> block would be blocked.
      if (/<style\b|\sstyle\s*=/i.test(text)) problems.push(`${rel}: has an inline style, which the CSP blocks. Use a class in site.css.`);
      // Checked on the final text, so the hash in the CSP always matches the script as written.
      const csp = (text.match(/<meta http-equiv="Content-Security-Policy" content="([^"]*)"/) || [])[1];
      if (!csp) problems.push(`${rel}: has no Content-Security-Policy meta tag`);
      else if (/'unsafe-inline'|'unsafe-eval'/.test(csp)) problems.push(`${rel}: the CSP allows 'unsafe-inline' or 'unsafe-eval'. Allow an inline script by its hash.`);
      const scriptSources = ((csp || "").match(/(?:^|;)\s*script-src\s([^;]*)/) || [])[1]?.trim().split(/\s+/) || [];
      for (const [, attrs, body] of text.matchAll(INLINE_SCRIPT)) {
        if (/\ssrc=|\stype="application\/ld\+json"/.test(attrs)) continue;
        if (!scriptSources.includes(scriptHash(body))) problems.push(`${rel}: an inline script's hash is not in the CSP script-src, so browsers would block it`);
      }
    }
    // Absolute URLs in meta tags, JSON-LD, and sitemap.xml.
    for (const [url] of text.matchAll(/https:\/\/pinkrynostudios\.com\/[^"'\s<>\\]*/g)) {
      if (!exists(url.slice(SITE.length))) problems.push(`${rel}: ${url} has no local file`);
    }
  }
  const css = readFileSync(join(root, "assets/css/site.css"), "utf8");
  for (const [, url] of css.matchAll(/url\(\s*["']?([^"')]+)["']?\s*\)/g)) {
    if (url.startsWith("data:")) continue;
    if (!/^\/(?!\/)/.test(url)) problems.push(`assets/css/site.css: url(${url}) must be an absolute site path`);
    else if (!exists(url)) problems.push(`assets/css/site.css: url(${url}) does not exist`);
    // Pictures come from the art maps and render as markup, so swapping art never means editing CSS.
    else if (!url.endsWith(".woff2")) problems.push(`assets/css/site.css: url(${url}) loads a picture. Add it to the art map in site.json and render it as markup.`);
  }
  must(!problems.length, "Nothing was written. Fix these references first:\n  " + problems.join("\n  "));
}

function removeStaleGamePages(visible) {
  const gamesDir = join(root, "games");
  if (!existsSync(gamesDir)) return;
  const keep = new Set(visible.map((game) => game.id));
  for (const entry of readdirSync(gamesDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (RESERVED.has(entry.name) || keep.has(entry.name)) continue;
    const indexPath = join(gamesDir, entry.name, "index.html");
    if (!existsSync(indexPath)) continue;
    const html = readFileSync(indexPath, "utf8");
    if (!html.includes(MARKER)) continue;
    rmSync(join(gamesDir, entry.name), { recursive: true, force: true });
    console.log("Removed stale generated page games/" + entry.name + "/");
  }
}

// An empty art slot leaves a whitespace-only line where its tag would be. Drop those lines.
function dropBlankLines(html) {
  return html.replace(/^[ \t]*\n/gm, "");
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  for (const key of ["site", "games"]) {
    if (options[key] !== join(root, key + ".json")) console.log(`Using ${options[key]} in place of ${key}.json.`);
  }
  // Both data files are checked before the release check, so a missing art file stops every mode.
  loadSite(options.site);
  const games = loadGames(options.games);
  if (options.release) {
    const missing = RELEASE_FIELDS.filter((key) => !studio[key]);
    if (missing.length) {
      console.error(
        "Release build refused. site.json is missing: " + missing.map((key) => "studio." + key).join(", ") + ".\n" +
        "Fill these in before the store-launch build. Nothing was written."
      );
      process.exit(1);
    }
  }
  year = options.lastmod.slice(0, 4);
  const visible = games.filter((game) => game.status !== "hidden");

  // Build everything first so a bad entry never leaves a half-written site.
  const files = [
    ["assets/css/themes.css", themesCss(games)],
    ["index.html", pageHome(visible)],
    ["games/index.html", pageGames(visible)],
    ...visible.map((game) => [`games/${game.id}/index.html`, pageGame(game)]),
    ["about/index.html", pageAbout(visible)],
    ["privacy/index.html", pagePrivacy()],
    ["support/index.html", pageSupport(visible)],
    ["404.html", pageNotFound()],
    ["sitemap.xml", sitemap(visible, options.lastmod)]
  ].map(([rel, text]) => [rel, rel.endsWith(".html") ? dropBlankLines(text) : text]);
  for (const [rel, html] of files) {
    must(!/\bTODO\b/.test(html), "Refusing to write " + rel + ": it contains TODO text");
  }
  checkRendered(files);
  removeStaleGamePages(visible);
  for (const [rel, html] of files) writeRel(rel, html);

  const omitted = RELEASE_FIELDS.filter((key) => !studio[key]);
  const mode = options.release ? "release" : "normal";
  console.log(`Rendered ${visible.length} game page(s) and the studio pages (${mode} build, sitemap date ${options.lastmod}).`);
  if (omitted.length) {
    console.log("Left out until set in site.json: " + omitted.map((key) => "studio." + key).join(", ") + ". Run with --release for the store launch.");
  }
  reportEmptySlots();
}

try {
  main();
} catch (error) {
  console.error("render-site: " + error.message);
  process.exit(1);
}
