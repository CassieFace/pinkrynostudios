/**
 * Renders the static PinkRyno Studios site from games.json and site.json.
 * Run from the repo root:
 *
 *   node scripts/render-site.mjs            Normal build. Leaves out anything that
 *                                           needs studio fields that are still null.
 *   node scripts/render-site.mjs --preview  Same as the normal build.
 *   node scripts/render-site.mjs --release  Store-launch build. Refuses to run, and
 *                                           writes nothing, until site.json
 *                                           studio.legalName, studio.address, and
 *                                           studio.supportEmail are all set.
 *   --lastmod=YYYY-MM-DD                    Date for sitemap.xml (default: today).
 *   --site=path/to/site.json                Read site data from another file (art reviews,
 *   --games=path/to/games.json              tests). Pages are still written to this repo.
 *
 * The mascot text, studio details, and the trust strip line come only from site.json.
 * Games come only from games.json. A game's Play in browser button, and every
 * line that talks about playing in the browser, render only when its
 * play_enabled is true and play_url is set. A game with no play_url renders no
 * play button; play_enabled true without a play_url stops the build.
 *
 * Brand: Meadow Path (Oct 28 2026). Every page shares the studio frame: the studio
 * logo (site.json art.headerLogo) and nav, the trust strip, and the sage hill footer
 * with the same logo.
 * Studio pages are cream, sage, and sky with no space imagery. A game page brings
 * its own world (games.json "world", a .world-<name> rule in site.css) inside its
 * hero only, and the rest of the page is the studio look again.
 *
 * Every picture comes from an art map: site.json "art" for site-wide art (Rosie,
 * the studio logo, favicons, logo, share image, icons) and each game's "art" in
 * games.json. This script holds no image paths. An art entry that is null (or
 * left out) is an empty slot: the element or section is left out, with no
 * placeholder and no gap, and the build lists the empty slots as a warning.
 * An entry that is set must point to a real file, in every build mode.
 *
 * The build also stops if a rendered page links to a missing local file or uses
 * a relative URL (404.html is served at any depth, so every URL must be absolute).
 *
 * Writes the pages and sitemap.xml.
 * Never writes CNAME, games/space-maze/, or games/tiny-trails-beta/.
 */

