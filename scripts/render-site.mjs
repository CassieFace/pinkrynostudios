function themesCss(games) {
  const lines = ["/* Generated from games.json accent colors. Used as the thin underline under each game title. */"];
  for (const game of games) {
    lines.push(`.game-${game.id}{--accent:${game.accent}}`);
  }
  return lines.join("\n") + "\n";
}

function sitemap(visible, lastmod) {
  const paths = ["/", "/games/", "/about/", "/privacy/", "/support/", ...visible.map((game) => game.page)];
  const urls = paths.map((path) => `  <url><loc>${SITE}${path}</loc><lastmod>${lastmod}</lastmod></url>`).join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;
}

function removeStaleGamePages(visible) {
  const gamesDir = join(root, "games");
  if (!existsSync(gamesDir)) return;
  const keep = new Set(visible.map((game) => game.id));
  for (const entry of readdirSync(gamesDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (RESERVED.has(entry.name) || keep.has(entry.name)) continue;
    const indexPath = join(gamesDir, entry.name, "index.html");
    if (!existsSync(indexPath)) continue;
    const html = readFileSync(indexPath, "utf8");
    if (!html.includes(MARKER)) continue;
    rmSync(join(gamesDir, entry.name), { recursive: true, force: true });
    console.log("Removed stale generated page games/" + entry.name + "/");
  }
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  loadSite();
  if (options.release) {
    const missing = RELEASE_FIELDS.filter((key) => !studio[key]);
    if (missing.length) {
      console.error(
        "Release build refused. site.json is missing: " + missing.map((key) => "studio." + key).join(", ") + ".\n" +
        "Fill these in before the store-launch build. Nothing was written."
      );
      process.exit(1);
    }
  }
  year = options.lastmod.slice(0, 4);
  const games = loadGames();
  const visible = games.filter((game) => game.status !== "hidden");

  // Build everything first so a bad entry never leaves a half-written site.
  const files = [
    ["assets/css/themes.css", themesCss(games)],
    ["index.html", pageHome(visible)],
    ["games/index.html", pageGames(visible)],
    ...visible.map((game) => [`games/${game.id}/index.html`, pageGame(game)]),
    ["about/index.html", pageAbout(visible)],
    ["privacy/index.html", pagePrivacy()],
    ["support/index.html", pageSupport(visible)],
    ["404.html", pageNotFound()],
    ["sitemap.xml", sitemap(visible, options.lastmod)]
  ];
  for (const [rel, html] of files) {
    must(!/\bTODO\b/.test(html), "Refusing to write " + rel + ": it contains TODO text");
  }
  removeStaleGamePages(visible);
  for (const [rel, html] of files) writeRel(rel, html);

  const omitted = RELEASE_FIELDS.filter((key) => !studio[key]);
  const mode = options.release ? "release" : "normal";
  console.log(`Rendered ${visible.length} game page(s) and the studio pages (${mode} build, sitemap date ${options.lastmod}).`);
  if (omitted.length) {
    console.log("Left out until set in site.json: " + omitted.map((key) => "studio." + key).join(", ") + ". Run with --release for the store launch.");
  }
}

try {
  main();
} catch (error) {
  console.error("render-site: " + error.message);
  process.exit(1);
}
