const GAME_TEXT = ["title", "tagline", "summary", "description", "free_content", "unlock"];

function loadGames(file) {
  const games = JSON.parse(readFileSync(file, "utf8"));
  must(Array.isArray(games) && games.length > 0, "games.json must be a non-empty array");
  const ids = new Set();
  for (const game of games) {
    must(game && typeof game === "object", "Each game must be an object");
    // `page` is written by this script; every other path must already exist.
    // Pictures belong in the game's art map, so no other field may hold a file path.
    for (const [src, label] of sitePaths(game)) {
      if (label === "page") continue;
      must(label === "play_url" || label.startsWith("art."), `games.json ${game.id} ${label}: pictures go in the game's "art" map`);
      requireFile(src, `games.json ${game.id} ${label}`);
    }
    must(/^[a-z][a-z0-9-]*$/.test(game.id), "Bad id: " + game.id);
    must(!RESERVED.has(game.id), game.id + " is a reserved path");
    must(!ids.has(game.id), "Duplicate id: " + game.id);
    ids.add(game.id);
    must(["live", "coming-soon", "hidden"].includes(game.status), game.id + " has a bad status");
    must(game.page === `/games/${game.id}/`, game.id + " page must be /games/" + game.id + "/");
    for (const key of GAME_TEXT) {
      must(typeof game[key] === "string" && game[key].trim(), game.id + " needs " + key);
    }
    game.short_title = textOrNull(game.short_title, game.id + " short_title") || game.title.split(":")[0].trim();
    must(typeof game.ages === "string" && /^\d+\s*[–-]\s*\d+$/.test(game.ages), game.id + " ages must look like 3–6");
    const [minAge, maxAge] = game.ages.split(/\s*[–-]\s*/).map(Number);
    game.ageRange = { min: minAge, max: maxAge };
    game.price = textOrNull(game.price, game.id + " price");
    if (game.price) must(/^\$\d+(\.\d\d)?$/.test(game.price), game.id + " price must look like $0.99 or be null");
    game.trial = textOrNull(game.trial, game.id + " trial");
    game.web_note = textOrNull(game.web_note, game.id + " web_note");
    game.play_size_note = textOrNull(game.play_size_note, game.id + " play_size_note");
    must(game.accent === undefined, `${game.id}: accent is gone (game titles no longer use an accent color). Use "world" to give the game page hero its own look.`);
    // world names the game page hero's look: a .world-<name> rule in site.css. null keeps the studio look.
    game.world = textOrNull(game.world, game.id + " world");
    if (game.world) {
      must(/^[a-z][a-z0-9-]*$/.test(game.world), game.id + " world must be a short lowercase name like space");
      must(siteCss().includes(`.world-${game.world}`), `${game.id} world "${game.world}" has no .world-${game.world} rule in assets/css/site.css`);
    }
    // studio_summary: the calm line on studio pages (home, games index), which show no game-world art or words.
    game.studio_summary = textOrNull(game.studio_summary, game.id + " studio_summary") || game.summary;
    must(Number.isFinite(game.order), game.id + " needs a numeric order");
    must(Array.isArray(game.highlights), game.id + " highlights must be an array");
    for (const item of game.highlights) {
      must(item && typeof item.text === "string" && item.text.trim(), game.id + " each highlight needs text");
      must(ICON_NAMES.includes(item.icon), game.id + " highlight icon must be one of " + ICON_NAMES.join(", "));
    }
    const copy = [...GAME_TEXT.map((key) => game[key]), game.studio_summary, game.trial, game.web_note, ...game.highlights.map((item) => item.text)];
    for (const text of copy) {
      must(!text || !PRIVACY_PITCH.test(text), `${game.id}: keep privacy and no-ads claims out of games.json ("${text}"). The trust strip covers it.`);
    }
    if (game.play_url != null && game.play_url !== "") {
      must(typeof game.play_url === "string" && /^\/(?!\/)/.test(game.play_url), game.id + " play_url must be a site path");
      must(!game.play_url.includes(".."), game.id + " play_url cannot contain ..");
      must(!game.play_url.startsWith("/games/tiny-trails-beta"), game.id + " cannot link to staging");
    } else {
      game.play_url = null;
    }
    must(game.play_enabled == null || typeof game.play_enabled === "boolean", game.id + " play_enabled must be true or false");
    must(
      game.play_enabled !== true || game.play_url,
      `games.json ${game.id} has "play_enabled": true but no play_url. Add the browser build's play_url (a page on this site), or set "play_enabled" to false.`
    );
    // Only play_enabled: true shows a play_url, so a game without it renders no browser-play wording.
    if (game.play_enabled !== true) game.play_url = null;
    game.play_label = textOrNull(game.play_label, game.id + " play_label") || "Play in browser";
    must(game.stores && typeof game.stores === "object", game.id + " needs stores");
    game.stores.ios = httpsOrNull(game.stores.ios, game.id + " stores.ios");
    game.stores.android = httpsOrNull(game.stores.android, game.id + " stores.android");
    must(game.art_alt === undefined, `${game.id}: art_alt is gone. Put each picture's alt text inside its art entry, like "hero": { "src": "...", "alt": "..." }.`);
    game.art = loadGameArt(game);
  }
  games.sort((a, b) => a.order - b.order || a.title.localeCompare(b.title));
  return games;
}

