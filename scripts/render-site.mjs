#!/usr/bin/env node
/**
 * Renders the static PinkRyno Studios site from games.json and site.json.
 * Run from the repo root:
 *
 *   node scripts/render-site.mjs            Normal build. Leaves out anything that
 *                                           needs studio fields that are still null.
 *   node scripts/render-site.mjs --preview  Same as the normal build.
 *   node scripts/render-site.mjs --release  Store-launch build. Refuses to run, and
 *                                           writes nothing, until site.json
 *                                           studio.legalName, studio.address, and
 *                                           studio.supportEmail are all set.
 *   --lastmod=YYYY-MM-DD                    Date for sitemap.xml (default: today).
 *
 * The mascot, studio details, and footer privacy line come only from site.json.
 * Games come only from games.json.
 *
 * Writes pages, assets/css/themes.css, and sitemap.xml.
 * Never writes CNAME, games/space-maze/, or games/tiny-trails-beta/.
 */

