function esc(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function must(condition, message) {
  if (!condition) throw new Error(message);
}

function writeRel(rel, contents) {
  const normalized = rel.replaceAll("\\", "/");
  if (
    normalized === "CNAME" ||
    normalized.startsWith("games/space-maze/") ||
    normalized.startsWith("games/tiny-trails-beta/")
  ) {
    throw new Error("Refusing to write " + normalized);
  }
  const abs = join(root, normalized);
  mkdirSync(dirname(abs), { recursive: true });
  const text = contents.endsWith("\n") ? contents : contents + "\n";
  writeFileSync(abs, text);
}

function publicFileExists(src) {
  must(src.startsWith("/"), "Asset path must start with /");
  return existsSync(join(root, src.slice(1)));
}

function httpsOrNull(value, label) {
  if (value == null || value === "") return null;
  must(typeof value === "string" && /^https:\/\/[^\s]+$/.test(value), label + " must be an https URL or null");
  must(!/[?&](utm_|fbclid|gclid|mc_eid)/i.test(value), label + " must not include tracking parameters");
  return value;
}

function loadGames() {
  const games = JSON.parse(readFileSync(join(root, "games.json"), "utf8"));
  must(Array.isArray(games) && games.length > 0, "games.json must be a non-empty array");
  const ids = new Set();
  for (const game of games) {
    must(game && typeof game === "object", "Each game must be an object");
    must(/^[a-z][a-z0-9-]*$/.test(game.id), "Bad id: " + game.id);
    must(!RESERVED.has(game.id), game.id + " is a reserved path");
    must(!ids.has(game.id), "Duplicate id: " + game.id);
    ids.add(game.id);
    must(["live", "coming-soon", "hidden"].includes(game.status), game.id + " has a bad status");
    must(game.page === `/games/${game.id}/`, game.id + " page must be /games/" + game.id + "/");
    must(typeof game.title === "string" && game.title.trim(), game.id + " needs a title");
    must(typeof game.tagline === "string" && game.tagline.trim(), game.id + " needs a tagline");
    must(typeof game.summary === "string" && game.summary.trim(), game.id + " needs a summary");
    must(typeof game.description === "string" && game.description.trim(), game.id + " needs a description");
    must(typeof game.ages === "string" && game.ages.trim(), game.id + " needs ages");
    must(typeof game.free_content === "string", game.id + " needs free_content");
    must(typeof game.unlock === "string", game.id + " needs unlock");
    must(/^#[0-9A-Fa-f]{6}$/.test(game.accent), game.id + " accent must be a #RRGGBB color");
    must(Number.isFinite(game.order), game.id + " needs a numeric order");
    must(Array.isArray(game.highlights), game.id + " highlights must be an array");
    if (game.play_url != null && game.play_url !== "") {
      must(typeof game.play_url === "string" && /^\/(?!\/)/.test(game.play_url), game.id + " play_url must be a site path");
      must(!game.play_url.includes(".."), game.id + " play_url cannot contain ..");
      must(!game.play_url.startsWith("/games/tiny-trails-beta"), game.id + " cannot link to staging");
    } else {
      game.play_url = null;
    }
    must(game.stores && typeof game.stores === "object", game.id + " needs stores");
    game.stores.ios = httpsOrNull(game.stores.ios, game.id + " stores.ios");
    game.stores.android = httpsOrNull(game.stores.android, game.id + " stores.android");
    must(game.art && game.art_alt && game.art_slots, game.id + " needs art, art_alt, and art_slots");
    for (const key of ["card", "hero"]) {
      must(typeof game.art[key] === "string", game.id + " missing art." + key);
      must(typeof game.art_alt[key] === "string", game.id + " missing art_alt." + key);
      must(typeof game.art_slots[key] === "string", game.id + " missing art_slots." + key);
    }
    must(Array.isArray(game.art.screens), game.id + " art.screens must be an array");
    must(game.art.screens.length === game.art_alt.screens.length, game.id + " screen alt count");
    must(game.art.screens.length === game.art_slots.screens.length, game.id + " screen slot count");
  }
  games.sort((a, b) => a.order - b.order || a.title.localeCompare(b.title));
  return games;
}

function loadMascot() {
  const site = JSON.parse(readFileSync(join(root, "site.json"), "utf8"));
  const next = site && site.mascot;
  must(next && typeof next.name === "string" && next.name.trim(), "site.json needs mascot.name");
  must(typeof next.fullName === "string" && next.fullName.trim(), "site.json needs mascot.fullName");
  must(next.pronouns && typeof next.pronouns.subject === "string" && next.pronouns.subject.trim(), "site.json needs mascot.pronouns.subject");
  must(typeof next.species === "string" && next.species.trim(), "site.json needs mascot.species");
  must(typeof next.alt === "string" && next.alt.trim(), "site.json needs mascot.alt");
  for (const key of ["full", "head", "social"]) {
    const image = next[key];
    must(image && typeof image.webp === "string" && image.webp.startsWith("/"), "site.json mascot." + key + ".webp");
    must(typeof image.png === "string" && image.png.startsWith("/"), "site.json mascot." + key + ".png");
    must(Number.isFinite(image.width) && Number.isFinite(image.height), "site.json mascot." + key + " size");
    must(publicFileExists(image.webp), "Missing mascot file " + image.webp);
    must(publicFileExists(image.png), "Missing mascot file " + image.png);
  }
  must(typeof next.favicon === "string" && next.favicon.startsWith("/"), "site.json needs mascot.favicon");
  must(publicFileExists(next.favicon), "Missing mascot file " + next.favicon);
  must(typeof next.appleTouch === "string" && next.appleTouch.startsWith("/"), "site.json needs mascot.appleTouch");
  must(publicFileExists(next.appleTouch), "Missing mascot file " + next.appleTouch);
  mascot = next;
}

function mascotAlt(detail) {
  const base = mascot.fullName + " " + mascot.alt;
  return detail ? base + ", " + detail : base;
}

function headPicture() {
  const head = mascot.head;
  return `<picture>
          <source srcset="${esc(head.webp)}" type="image/webp">
          <img src="${esc(head.png)}" alt="" width="${head.width}" height="${head.height}">
        </picture>`;
}

function mascotPicture(detail, eager) {
  const extra = eager ? ' fetchpriority="high"' : ' loading="lazy"';
  const full = mascot.full;
  return `<picture>
          <source srcset="${esc(full.webp)}" type="image/webp">
          <img src="${esc(full.png)}" alt="${esc(mascotAlt(detail))}" width="${full.width}" height="${full.height}"${extra}>
        </picture>`;
}

function media({ src, alt, slotId, slotLabel, width, height, frameClass, eager }) {
  let inner;
  if (publicFileExists(src)) {
    const extra = eager ? ' fetchpriority="high"' : ' loading="lazy"';
    inner = `<img src="${esc(src)}" alt="${esc(alt)}" width="${width}" height="${height}"${extra}>`;
  } else {
    const label = `Illustration not added yet. Slot ${slotId}. ${slotLabel}. Planned picture: ${alt}`;
    inner = `<div class="art-slot" role="img" aria-label="${esc(label)}"><p class="art-slot-card" aria-hidden="true"><span class="art-slot-id">${esc(slotId)}</span> <span class="art-slot-label">${esc(slotLabel)}</span></p></div>`;
  }
  return `<div class="frame ${frameClass}">${inner}</div>`;
}

function gameMedia(game, kind, frameClass, eager, index) {
  if (kind === "screen") {
    return media({
      src: game.art.screens[index],
      alt: game.art_alt.screens[index],
      slotId: game.art_slots.screens[index],
      slotLabel: game.title + " scene",
      width: 1200,
      height: 900,
      frameClass,
      eager
    });
  }
  const wide = kind === "hero";
  return media({
    src: game.art[kind],
    alt: game.art_alt[kind],
    slotId: game.art_slots[kind],
    slotLabel: wide ? game.title + " key art" : game.title + " card",
    width: wide ? 1280 : 1280,
    height: wide ? 720 : 800,
    frameClass,
    eager
  });
}

function chips(game) {
  const statusClass = game.status === "live" ? "chip chip-mint" : "chip chip-peach";
  const statusLabel = game.status === "live" ? "Ready to play" : "Coming soon";
  return `<div class="chips"><span class="chip chip-lavender">Ages ${esc(game.ages)}</span> <span class="${statusClass}">${statusLabel}</span></div>`;
}

function storeLink(url, label) {
  return `<a class="btn btn-store" href="${esc(url)}" data-parent-gate>${esc(label)}<span class="visually-hidden"> (leaves this website, a grown-up answers first)</span></a>`;
}

function mailLink(className) {
  const cls = className ? ` class="${className}"` : "";
  return `<a href="mailto:${esc(SUPPORT_EMAIL)}"${cls} data-parent-gate>${esc(SUPPORT_EMAIL)}<span class="visually-hidden"> (leaves this website, a grown-up answers first)</span></a>`;
}

function actions(game, includePageLink, showNote) {
  const bits = [];
  if (game.play_url) {
    bits.push(`<a class="btn btn-play" href="${esc(game.play_url)}">${esc(game.play_label || "Play in browser")}</a>`);
  }
  if (includePageLink) {
    bits.push(`<a class="btn" href="${esc(game.page)}">About this game</a>`);
  }
  if (game.stores.ios) bits.push(storeLink(game.stores.ios, "App Store"));
  if (game.stores.android) bits.push(storeLink(game.stores.android, "Google Play"));
  let note = "";
  if (showNote && game.status === "coming-soon") {
    note = `<p>This game is still being made. It will show up here when it is ready to play.</p>`;
  } else if (showNote && !game.stores.ios && !game.stores.android) {
    note = `<p>App Store and Google Play buttons appear here when those listings are live.</p>`;
  }
  if (!bits.length && !note) {
    note = `<p>Play links will appear here when they are ready.</p>`;
  }
  return `<div class="cta-row">${bits.join("\n")}</div>\n${note}`;
}

function card(game) {
  return `<article class="card game-${esc(game.id)}">
        ${gameMedia(game, "card", "frame-card", false)}
        <div class="card-body">
          ${chips(game)}
          <h2 class="card-title"><a href="${esc(game.page)}">${esc(game.title)}</a></h2>
          <p>${esc(game.tagline)}</p>
          ${actions(game, false)}
        </div>
      </article>`;
}

function jsonLd(data) {
  const json = JSON.stringify(data).replaceAll("<", "\\u003c");
  return `<script type="application/ld+json">${json}</script>`;
}

