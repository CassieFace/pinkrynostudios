function publicFileExists(src) {
  if (typeof src !== "string" || src === "") return false;
  must(src.startsWith("/"), "Asset path must start with /: " + src);
  return existsSync(join(root, src.slice(1)));
}

// The repo-relative file a site path is served from ("/games/" -> "games/index.html").
function sitePathToRel(src) {
  let clean = src.split(/[?#]/)[0];
  try {
    clean = decodeURIComponent(clean);
  } catch {
    // Leave it encoded; it will not match a file and the caller reports it.
  }
  const rel = clean.slice(1);
  return rel === "" || rel.endsWith("/") ? rel + "index.html" : rel;
}

// A site path from site.json or games.json. It must exist; null is handled by the caller.
function requireFile(src, label) {
  must(typeof src === "string" && /^\/(?!\/)/.test(src), label + " must be a site path that starts with / (or null)");
  must(!src.includes(".."), label + " cannot contain ..");
  must(!retired.has(src.split("#")[0]), `${label} uses retired off-model art (${src}). Set it to null until approved art exists.`);
  must(existsSync(join(root, sitePathToRel(src))), `${label} points to ${src}, which does not exist. Add the file or set the field to null.`);
  return src;
}

// Every string in a JSON value that looks like a site path, with its key path ("art.screenshots[0]").
function sitePaths(value, label = "", out = []) {
  if (typeof value === "string") {
    if (/^\/(?!\/)/.test(value)) out.push([value, label]);
  } else if (Array.isArray(value)) {
    value.forEach((item, index) => sitePaths(item, `${label}[${index}]`, out));
  } else if (value && typeof value === "object") {
    for (const [key, item] of Object.entries(value)) sitePaths(item, label ? `${label}.${key}` : key, out);
  }
  return out;
}

function webpSize(src) {
  const buf = readFileSync(join(root, src.slice(1)));
  must(buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP", "Not a WebP: " + src);
  const chunk = buf.toString("ascii", 12, 16);
  if (chunk === "VP8X") return [1 + buf.readUIntLE(24, 3), 1 + buf.readUIntLE(27, 3)];
  if (chunk === "VP8 ") return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff];
  if (chunk === "VP8L") {
    const b0 = buf[21], b1 = buf[22], b2 = buf[23], b3 = buf[24];
    return [1 + (((b1 & 0x3f) << 8) | b0), 1 + (((b3 & 0x0f) << 10) | (b2 << 2) | ((b1 & 0xc0) >> 6))];
  }
  throw new Error("Unknown WebP layout: " + src);
}

function pngSize(src) {
  const buf = readFileSync(join(root, src.slice(1)));
  must(buf.readUInt32BE(0) === 0x89504e47 && buf.toString("ascii", 12, 16) === "IHDR", "Not a PNG: " + src);
  return [buf.readUInt32BE(16), buf.readUInt32BE(20)];
}

function jpegSize(src) {
  const buf = readFileSync(join(root, src.slice(1)));
  must(buf[0] === 0xff && buf[1] === 0xd8, "Not a JPEG: " + src);
  let i = 2;
  while (i < buf.length) {
    if (buf[i] !== 0xff) { i++; continue; }
    const marker = buf[i + 1];
    const length = buf.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return [buf.readUInt16BE(i + 7), buf.readUInt16BE(i + 5)];
    }
    i += 2 + length;
  }
  throw new Error("No size in JPEG: " + src);
}

// The pixel sizes of the images inside an .ico, smallest first. Each must be square.
function icoSizes(src) {
  const buf = readFileSync(join(root, src.slice(1)));
  must(buf.length >= 6 && buf.readUInt16LE(0) === 0 && buf.readUInt16LE(2) === 1 && buf.readUInt16LE(4) > 0, "Not an ICO: " + src);
  const sizes = [];
  for (let index = 0; index < buf.readUInt16LE(4); index++) {
    const at = 6 + 16 * index;
    must(at + 16 <= buf.length, "Truncated ICO: " + src);
    // A stored 0 means 256 px.
    const width = buf[at] || 256;
    const height = buf[at + 1] || 256;
    must(width === height, `${src} has a ${width}x${height} image, but favicon images must be square`);
    sizes.push(width);
  }
  return [...new Set(sizes)].sort((a, b) => a - b);
}

// An SVG's size is the pixel width and height on its root element (outlined title art).
function svgSize(src) {
  const text = readFileSync(join(root, src.slice(1)), "utf8");
  const tag = (text.match(/<svg\b[^>]*>/) || [""])[0];
  const read = (name) => Number((tag.match(new RegExp(`\\s${name}="(\\d+(?:\\.\\d+)?)(?:px)?"`)) || [])[1]);
  const size = [read("width"), read("height")];
  must(size.every((n) => n > 0), `${src} needs pixel width and height attributes on its <svg> element`);
  return size;
}

function imageSize(src) {
  if (src.endsWith(".webp")) return webpSize(src);
  if (src.endsWith(".png")) return pngSize(src);
  if (/\.jpe?g$/.test(src)) return jpegSize(src);
  if (src.endsWith(".svg")) return svgSize(src);
  throw new Error("Use .webp, .png, .jpg, or .svg for " + src);
}

function httpsOrNull(value, label) {
  if (value == null || value === "") return null;
  must(typeof value === "string" && /^https:\/\/[^\s]+$/.test(value), label + " must be an https URL or null");
  must(!/[?&](utm_|fbclid|gclid|mc_eid)/i.test(value), label + " must not include tracking parameters");
  return value;
}

function textOrNull(value, label) {
  if (value == null || value === "") return null;
  must(typeof value === "string" && value.trim(), label + " must be text or null");
  return value.trim();
}

function today() {
  const now = new Date();
  const pad = (n) => String(n).padStart(2, "0");
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

function parseArgs(argv) {
  const options = { release: false, preview: false, lastmod: today(), site: join(root, "site.json"), games: join(root, "games.json") };
  for (const arg of argv) {
    if (arg === "--release") options.release = true;
    else if (arg === "--preview") options.preview = true;
    else if (arg.startsWith("--lastmod=")) options.lastmod = arg.slice("--lastmod=".length);
    else if (arg.startsWith("--site=")) options.site = resolve(arg.slice("--site=".length));
    else if (arg.startsWith("--games=")) options.games = resolve(arg.slice("--games=".length));
    else throw new Error(`Unknown option ${arg}. Use --release, --preview, --lastmod=YYYY-MM-DD, --site=FILE, or --games=FILE.`);
  }
  for (const key of ["site", "games"]) must(existsSync(options[key]), `--${key}: ${options[key]} does not exist`);
  must(!(options.release && options.preview), "Use either --release or --preview, not both.");
  must(/^\d{4}-\d{2}-\d{2}$/.test(options.lastmod) && !Number.isNaN(Date.parse(options.lastmod)), "--lastmod must be a date like 2026-10-27");
  return options;
}

