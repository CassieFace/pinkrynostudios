function esc(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function must(condition, message) {
  if (!condition) throw new Error(message);
}

function writeRel(rel, contents) {
  const normalized = rel.replaceAll("\\", "/");
  if (
    normalized === "CNAME" ||
    normalized.startsWith("games/space-maze/") ||
    normalized.startsWith("games/tiny-trails-beta/")
  ) {
    throw new Error("Refusing to write " + normalized);
  }
  const abs = join(root, normalized);
  mkdirSync(dirname(abs), { recursive: true });
  const text = contents.endsWith("\n") ? contents : contents + "\n";
  writeFileSync(abs, text);
}

function publicFileExists(src) {
  if (typeof src !== "string" || src === "") return false;
  must(src.startsWith("/"), "Asset path must start with /: " + src);
  return existsSync(join(root, src.slice(1)));
}

function webpSize(src) {
  const buf = readFileSync(join(root, src.slice(1)));
  must(buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP", "Not a WebP: " + src);
  const chunk = buf.toString("ascii", 12, 16);
  if (chunk === "VP8X") return [1 + buf.readUIntLE(24, 3), 1 + buf.readUIntLE(27, 3)];
  if (chunk === "VP8 ") return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff];
  if (chunk === "VP8L") {
    const b0 = buf[21], b1 = buf[22], b2 = buf[23], b3 = buf[24];
    return [1 + (((b1 & 0x3f) << 8) | b0), 1 + (((b3 & 0x0f) << 10) | (b2 << 2) | ((b1 & 0xc0) >> 6))];
  }
  throw new Error("Unknown WebP layout: " + src);
}

function pngSize(src) {
  const buf = readFileSync(join(root, src.slice(1)));
  must(buf.readUInt32BE(0) === 0x89504e47 && buf.toString("ascii", 12, 16) === "IHDR", "Not a PNG: " + src);
  return [buf.readUInt32BE(16), buf.readUInt32BE(20)];
}

function jpegSize(src) {
  const buf = readFileSync(join(root, src.slice(1)));
  must(buf[0] === 0xff && buf[1] === 0xd8, "Not a JPEG: " + src);
  let i = 2;
  while (i < buf.length) {
    if (buf[i] !== 0xff) { i++; continue; }
    const marker = buf[i + 1];
    const length = buf.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return [buf.readUInt16BE(i + 7), buf.readUInt16BE(i + 5)];
    }
    i += 2 + length;
  }
  throw new Error("No size in JPEG: " + src);
}

function imageSize(src) {
  if (src.endsWith(".webp")) return webpSize(src);
  if (src.endsWith(".png")) return pngSize(src);
  if (/\.jpe?g$/.test(src)) return jpegSize(src);
  throw new Error("Use .webp, .png, or .jpg for " + src);
}

function httpsOrNull(value, label) {
  if (value == null || value === "") return null;
  must(typeof value === "string" && /^https:\/\/[^\s]+$/.test(value), label + " must be an https URL or null");
  must(!/[?&](utm_|fbclid|gclid|mc_eid)/i.test(value), label + " must not include tracking parameters");
  return value;
}

function textOrNull(value, label) {
  if (value == null || value === "") return null;
  must(typeof value === "string" && value.trim(), label + " must be text or null");
  return value.trim();
}

function today() {
  const now = new Date();
  const pad = (n) => String(n).padStart(2, "0");
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

function parseArgs(argv) {
  const options = { release: false, preview: false, lastmod: today() };
  for (const arg of argv) {
    if (arg === "--release") options.release = true;
    else if (arg === "--preview") options.preview = true;
    else if (arg.startsWith("--lastmod=")) options.lastmod = arg.slice("--lastmod=".length);
    else throw new Error(`Unknown option ${arg}. Use --release, --preview, or --lastmod=YYYY-MM-DD.`);
  }
  must(!(options.release && options.preview), "Use either --release or --preview, not both.");
  must(/^\d{4}-\d{2}-\d{2}$/.test(options.lastmod) && !Number.isNaN(Date.parse(options.lastmod)), "--lastmod must be a date like 2026-10-27");
  return options;
}

/* games.json ------------------------------------------------------------ */

const GAME_TEXT = ["title", "tagline", "summary", "description", "free_content", "unlock"];

function loadGames() {
  const games = JSON.parse(readFileSync(join(root, "games.json"), "utf8"));
  must(Array.isArray(games) && games.length > 0, "games.json must be a non-empty array");
  const ids = new Set();
  for (const game of games) {
    must(game && typeof game === "object", "Each game must be an object");
    must(/^[a-z][a-z0-9-]*$/.test(game.id), "Bad id: " + game.id);
    must(!RESERVED.has(game.id), game.id + " is a reserved path");
    must(!ids.has(game.id), "Duplicate id: " + game.id);
    ids.add(game.id);
    must(["live", "coming-soon", "hidden"].includes(game.status), game.id + " has a bad status");
    must(game.page === `/games/${game.id}/`, game.id + " page must be /games/" + game.id + "/");
    for (const key of GAME_TEXT) {
      must(typeof game[key] === "string" && game[key].trim(), game.id + " needs " + key);
    }
    game.short_title = textOrNull(game.short_title, game.id + " short_title") || game.title.split(":")[0].trim();
    must(typeof game.ages === "string" && /^\d+\s*[–-]\s*\d+$/.test(game.ages), game.id + " ages must look like 3–6");
    const [minAge, maxAge] = game.ages.split(/\s*[–-]\s*/).map(Number);
    game.ageRange = { min: minAge, max: maxAge };
    game.price = textOrNull(game.price, game.id + " price");
    if (game.price) must(/^\$\d+(\.\d\d)?$/.test(game.price), game.id + " price must look like $0.99 or be null");
    game.trial = textOrNull(game.trial, game.id + " trial");
    game.web_note = textOrNull(game.web_note, game.id + " web_note");
    game.play_size_note = textOrNull(game.play_size_note, game.id + " play_size_note");
    must(/^#[0-9A-Fa-f]{6}$/.test(game.accent), game.id + " accent must be a #RRGGBB color");
    must(Number.isFinite(game.order), game.id + " needs a numeric order");
    must(Array.isArray(game.highlights), game.id + " highlights must be an array");
    for (const item of game.highlights) {
      must(item && typeof item.text === "string" && item.text.trim(), game.id + " each highlight needs text");
      must(ICON_PATHS[item.icon], game.id + " highlight icon must be one of " + Object.keys(ICON_PATHS).join(", "));
    }
    const copy = [...GAME_TEXT.map((key) => game[key]), game.trial, game.web_note, ...game.highlights.map((item) => item.text)];
    for (const text of copy) {
      must(!text || !PRIVACY_PITCH.test(text), `${game.id}: keep privacy and no-ads claims out of games.json ("${text}"). The footer line covers it.`);
    }
    if (game.play_url != null && game.play_url !== "") {
      must(typeof game.play_url === "string" && /^\/(?!\/)/.test(game.play_url), game.id + " play_url must be a site path");
      must(!game.play_url.includes(".."), game.id + " play_url cannot contain ..");
      must(!game.play_url.startsWith("/games/tiny-trails-beta"), game.id + " cannot link to staging");
    } else {
      game.play_url = null;
    }
    game.play_label = textOrNull(game.play_label, game.id + " play_label") || "Play in browser";
    must(game.stores && typeof game.stores === "object", game.id + " needs stores");
    game.stores.ios = httpsOrNull(game.stores.ios, game.id + " stores.ios");
    game.stores.android = httpsOrNull(game.stores.android, game.id + " stores.android");
    must(game.art && typeof game.art === "object", game.id + " needs art");
    game.art_alt = game.art_alt || {};
    game.art.screens = game.art.screens || [];
    game.art_alt.screens = game.art_alt.screens || [];
    must(Array.isArray(game.art.screens) && Array.isArray(game.art_alt.screens), game.id + " art.screens and art_alt.screens must be arrays");
    must(game.art.screens.length === game.art_alt.screens.length, game.id + " needs one art_alt.screens entry per screen");
    for (const key of ["hero", "card", "og"]) {
      const src = game.art[key];
      must(src == null || (typeof src === "string" && src.startsWith("/")), game.id + " art." + key + " must be a site path or null");
      if (publicFileExists(src)) must(typeof game.art_alt[key] === "string" && game.art_alt[key].trim(), game.id + " needs art_alt." + key);
    }
  }
  games.sort((a, b) => a.order - b.order || a.title.localeCompare(b.title));
  return games;
}

/* site.json ------------------------------------------------------------- */

function checkImage(image, label, kinds = ["webp"]) {
  must(image && typeof image === "object", "site.json needs " + label);
  for (const kind of kinds) {
    must(typeof image[kind] === "string" && image[kind].startsWith("/"), `site.json ${label}.${kind}`);
    must(publicFileExists(image[kind]), "Missing mascot file " + image[kind]);
  }
  must(Number.isFinite(image.width) && Number.isFinite(image.height), `site.json ${label} needs width and height`);
}

function loadSite() {
  const site = JSON.parse(readFileSync(join(root, "site.json"), "utf8"));
  const next = site && site.mascot;
  must(next && typeof next.name === "string" && next.name.trim(), "site.json needs mascot.name");
  must(typeof next.fullName === "string" && next.fullName.trim(), "site.json needs mascot.fullName");
  must(next.pronouns && typeof next.pronouns.subject === "string" && next.pronouns.subject.trim(), "site.json needs mascot.pronouns.subject");
  must(typeof next.species === "string" && next.species.trim(), "site.json needs mascot.species");
  must(typeof next.alt === "string" && next.alt.trim(), "site.json needs mascot.alt");
  checkImage(next.full, "mascot.full", ["webp", "png"]);
  checkImage(next.head, "mascot.head", ["webp", "png"]);
  checkImage(next.icon, "mascot.icon");
  checkImage(next.social, "mascot.social", ["webp", "png"]);
  for (const size of ["large", "small"]) {
    const hero = next.hero && next.hero[size];
    checkImage(hero, "mascot.hero." + size, ["anim", "still"]);
    for (const kind of ["anim", "still"]) {
      const [w, h] = webpSize(hero[kind]);
      must(w === hero.width && h === hero.height, `site.json mascot.hero.${size} says ${hero.width}x${hero.height}, but ${hero[kind]} is ${w}x${h}`);
    }
  }
  for (const key of ["favicon", "appleTouch"]) {
    must(typeof next[key] === "string" && next[key].startsWith("/"), "site.json needs mascot." + key);
    must(publicFileExists(next[key]), "Missing mascot file " + next[key]);
  }
  mascot = next;

  const info = site.studio;
  must(info && typeof info === "object", "site.json needs a studio object");
  studio = {
    legalName: textOrNull(info.legalName, "site.json studio.legalName"),
    address: textOrNull(info.address, "site.json studio.address"),
    supportEmail: textOrNull(info.supportEmail, "site.json studio.supportEmail")
  };
  if (studio.supportEmail) {
    must(/^[^\s@<>"]+@[^\s@<>"]+\.[a-z]{2,}$/i.test(studio.supportEmail), "site.json studio.supportEmail must be an email address or null");
  }
  privacyLine = textOrNull(site.privacyLine, "site.json privacyLine");
  must(privacyLine, "site.json needs privacyLine (the one footer line about privacy)");
}

/* Shared pieces --------------------------------------------------------- */

function mascotAlt() {
  return mascot.fullName + " " + mascot.alt;
}

// size is the CSS display size. The 128 px icon covers 2x screens up to 64 px;
// bigger spots also offer the 256 px head.
function iconImg(className, lazy, size) {
  const { icon, head } = mascot;
  const loading = lazy ? ' loading="lazy"' : "";
  const srcset = size * 2 > icon.width ? ` srcset="${esc(icon.webp)} ${icon.width}w, ${esc(head.webp)} ${head.width}w" sizes="${size}px"` : "";
  return `<img class="${className}" src="${esc(icon.webp)}"${srcset} alt="" width="${icon.width}" height="${icon.height}"${loading}>`;
}

function fullImg(className, alt, lazy) {
  const full = mascot.full;
  const loading = lazy ? ' loading="lazy"' : "";
  return `<img class="${className}" src="${esc(full.webp)}" alt="${esc(alt)}" width="${full.width}" height="${full.height}"${loading}>`;
}

// Phone layout below this width. Keep in step with the 760px breakpoint in site.css.
const PHONE = "(max-width: 760px)";
const REDUCE = "(prefers-reduced-motion: reduce)";

function heroPicture() {
  const { large, small } = mascot.hero;
  const alt = `${mascot.fullName}, a baby ${mascot.species}, waving hello`;
  return `<picture>
          <source media="${PHONE} and ${REDUCE}" srcset="${esc(small.still)}" type="image/webp" width="${small.width}" height="${small.height}">
          <source media="${PHONE}" srcset="${esc(small.anim)}" type="image/webp" width="${small.width}" height="${small.height}">
          <source media="${REDUCE}" srcset="${esc(large.still)}" type="image/webp" width="${large.width}" height="${large.height}">
          <img src="${esc(large.anim)}" alt="${esc(alt)}" width="${large.width}" height="${large.height}" fetchpriority="high">
        </picture>`;
}

function heroPreloads() {
  const { large, small } = mascot.hero;
  const motion = "(prefers-reduced-motion: no-preference)";
  const wide = "(min-width: 761px)";
  return [
    [large.anim, `${wide} and ${motion}`],
    [large.still, `${wide} and ${REDUCE}`],
    [small.anim, `${PHONE} and ${motion}`],
    [small.still, `${PHONE} and ${REDUCE}`]
  ].map(([href, media]) => `<link rel="preload" href="${esc(href)}" as="image" type="image/webp" media="${media}">`).join("\n") + "\n";
}

const LEAVES = '<span class="visually-hidden"> (leaves this website, a grown-up answers first)</span>';
const OPENS_MAIL = '<span class="visually-hidden"> (opens your email app, a grown-up answers first)</span>';

function mailLink(className) {
  if (!studio.supportEmail) return "";
  const cls = className ? ` class="${className}"` : "";
  return `<a${cls} href="mailto:${esc(studio.supportEmail)}" data-parent-gate>${esc(studio.supportEmail)}${OPENS_MAIL}</a>`;
}

function more(href, label) {
  return `<a class="more" href="${esc(href)}">${esc(label)}</a>`;
}

function storeLinks(game) {
  const links = [];
  if (game.stores.ios) links.push(`<a class="store-link" href="${esc(game.stores.ios)}" data-parent-gate>Get it on the App Store${LEAVES}</a>`);
  if (game.stores.android) links.push(`<a class="store-link" href="${esc(game.stores.android)}" data-parent-gate>Get it on Google Play${LEAVES}</a>`);
  return links.join("\n");
}

function storeLine(game) {
  const missing = [];
  if (!game.stores.ios) missing.push("iPhone", "iPad");
  if (!game.stores.android) missing.push("Android");
  if (!missing.length || game.status !== "live") return "";
  const list = missing.length > 1 ? missing.slice(0, -1).join(", ") + " and " + missing.at(-1) : missing[0];
  return `<p class="store-line">Coming soon to ${list}.</p>`;
}

function priceLabel(game) {
  return game.price ? `${game.price} one-time unlock` : "One-time unlock";
}

function metaLine(game) {
  if (game.status === "coming-soon") return `<p class="meta">Ages ${esc(game.ages)} · Coming soon</p>`;
  return `<p class="meta">Ages ${esc(game.ages)} · Free to start · ${esc(priceLabel(game))}</p>`;
}

function playButton(game) {
  if (!game.play_url || game.status !== "live") return "";
  return `<a class="btn" href="${esc(game.play_url)}">${esc(game.play_label)}</a>`;
}

function gameFeature(game, { level, id, onPage }) {
  const tag = level === 1 ? "h1" : "h2";
  const title = onPage ? esc(game.title) : `<a href="${esc(game.page)}">${esc(game.title)}</a>`;
  const actions = [playButton(game), onPage ? "" : more(game.page, "More about " + game.short_title), storeLinks(game)].filter(Boolean);
  const sizeNote = onPage && game.play_url && game.play_size_note && game.status === "live"
    ? `<p class="size-note">Plays right in your browser · ${esc(game.play_size_note)}</p>`
    : "";
  let art = "";
  if (publicFileExists(game.art.hero)) {
    const [width, height] = imageSize(game.art.hero);
    const priority = onPage ? ' fetchpriority="high"' : ' loading="lazy"';
    art = `<img class="feature-art" src="${esc(game.art.hero)}" alt="${esc(game.art_alt.hero)}" width="${width}" height="${height}"${priority}>\n          `;
  }
  const crumbs = onPage
    ? `<nav class="crumbs" aria-label="Breadcrumb"><a href="/games/">Games</a> <span aria-hidden="true">/</span> <span aria-current="page">${esc(game.title)}</span></nav>\n      `
    : "";
  return `<div class="wrap">
      ${crumbs}<div class="feature-grid">
        <div class="feature-head">
          ${art}<${tag} id="${id}" class="feature-title accent-title">${title}</${tag}>
          <p class="feature-tagline">${esc(game.tagline)}</p>
        </div>
        <div class="feature-body">
          ${[
            `<p>${esc(game.summary)}</p>`,
            metaLine(game),
            actions.length ? `<div class="cta-row">\n            ${actions.join("\n            ")}\n          </div>` : "",
            sizeNote,
            storeLine(game)
          ].filter(Boolean).join("\n          ")}
        </div>
      </div>
    </div>`;
}

function jsonLd(data) {
  const json = JSON.stringify(data).replaceAll("<", "\\u003c");
  return `<script type="application/ld+json">${json}</script>`;
}

function socialImage() {
  return { url: SITE + mascot.social.png, width: mascot.social.width, height: mascot.social.height, type: "image/png", alt: mascotAlt() };
}

function gameSocialImage(game) {
  const src = game.art.og;
  if (!publicFileExists(src)) return socialImage();
  const [width, height] = imageSize(src);
  const type = src.endsWith(".png") ? "image/png" : src.endsWith(".webp") ? "image/webp" : "image/jpeg";
  return { url: SITE + src, width, height, type, alt: game.art_alt.og };
}

